import fs from 'node:fs'
import { join, resolve } from 'pathe'
import type { UnpluginOptions } from 'unplugin'
import type { NuxtUIOptions } from '../unplugin'
import { findAddedColors, getColorsDeclaration } from '../utils/tailwind'

/**
 * This plugin writes `ui.d.ts` next to `components.d.ts`, which types the
 * colors the app adds in `@plugin "@nuxt/ui/colors"` in every `color` prop.
 */
export default function ColorsPlugin(options: NuxtUIOptions): UnpluginOptions {
  let file: string | undefined
  // The colors of each stylesheet Vite loads, the ones it imports included:
  // Tailwind CSS inlines those, so Vite never loads them itself
  const added = new Map<string, string[]>()

  return {
    name: 'nuxt:ui:colors',
    enforce: 'pre',
    vite: {
      configResolved(config) {
        file = join(resolve(options.root || config.root), 'ui.d.ts')
      }
    },
    transformInclude: id => /\.css(?:\?|$)/.test(id) && !id.includes('/node_modules/'),
    async transform(_, id) {
      if (options.dts === false || !file) {
        return
      }

      // One entry per file, whichever query Vite loads it with
      const path = id.replace(/\?.*$/, '')
      added.set(path, await findAddedColors([path]))
      const names = [...new Set([...added.values()].flat())]

      // Only an app that adds a color gets the file, and keeps it once it has it
      const exists = fs.existsSync(file)
      if (!names.length && !exists) {
        return
      }
      const contents = `// Generated by Nuxt UI from \`@plugin "@nuxt/ui/colors"\`\n${getColorsDeclaration(names)}\nexport {}\n`
      if (!exists || fs.readFileSync(file, 'utf8') !== contents) {
        fs.writeFileSync(file, contents)
      }
    }
  }
}
